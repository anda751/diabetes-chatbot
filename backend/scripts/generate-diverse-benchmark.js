const prefixes = ["", "ขอถามหน่อยค่ะ ", "รบกวนแนะนำหน่อยครับ ", "ช่วยอธิบายแบบเข้าใจง่ายหน่อย ", "อยากทราบว่า "];
const suffixes = ["", " ควรเริ่มจากอะไร", " มีข้อควรระวังอะไรบ้าง", " ขอคำตอบสั้น ๆ ก็ได้", " ช่วยบอกแนวทางที่ทำได้วันนี้"];
const contexts = ["", " ตอนเช้า", " หลังมื้อเย็น", " ระหว่างทำงาน", " อยู่คนเดียวที่บ้าน", " กำลังจะไปพบแพทย์สัปดาห์หน้า"];

function escapeCsv(value) {
  return `"${String(value ?? "").replace(/"/g, '""')}"`;
}

function makeQuestion(seed, index) {
  const prefix = prefixes[index % prefixes.length];
  const suffix = suffixes[Math.floor(index / prefixes.length) % suffixes.length];
  const context = contexts[Math.floor(index / (prefixes.length * suffixes.length)) % contexts.length];
  return `${prefix}${seed}${context}${suffix}`.replace(/\s+/g, " ").trim();
}

function buildRows(total) {
  const rows = [];
  let index = 0;
  while (rows.length < total) {
    const [intentKey, intentLabel] = intents[index % intents.length];
    const seeds = scenarios[intentKey];
    const seed = seeds[Math.floor(index / intents.length) % seeds.length];
    const cycle = Math.floor(index / (intents.length * seeds.length));
    rows.push({
      row_id: rows.length + 1,
      question_text: makeQuestion(seed, cycle + rows.length),
      expected_intent_key: intentKey,
      expected_intent_label: intentLabel,
      source: "synthetic-authored-scenario",
    });
    index += 1;
  }
  return rows;
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const total = Number(process.env.BENCHMARK_TOTAL || 100);
const outputPath = path.resolve(
  process.env.BENCHMARK_OUTPUT_PATH || path.join(root, "generated", "evaluation-benchmark-diverse-100.csv")
);
const rows = buildRows(total);
const headers = Object.keys(rows[0]);
const csv = `\uFEFF${[headers, ...rows.map((row) => headers.map((header) => row[header]))]
  .map((row) => row.map(escapeCsv).join(","))
  .join("\n")}\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, csv, "utf8");
console.log(`Generated ${rows.length} diverse benchmark questions: ${outputPath}`);
